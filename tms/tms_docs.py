        f"Generated: {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}",
        "",
        f"Shipper: {shipment.get('shipper_name', '-')}",
        f"Consignee: {shipment.get('consignee_name', '-')}",
        f"Origin: {shipment.get('origin_port', '-')}",
        f"Destination: {shipment.get('destination_port', '-')}",
        f"Status: {shipment.get('status', 'Draft')}",
        f"Cargo: {shipment.get('cargo_description', '-')}",
        f"Containers: {shipment.get('containers', '-')}",
        f"Weight (kg): {shipment.get('weight_kg') or 0}",
