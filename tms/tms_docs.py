# ── AIR WAYBILL ───────────────────────────────────────────────────────────────
def _awb_number(shipment_ref: str) -> str:
    """Generate a deterministic AWB number in format XXX-XXXXXXXX from shipment ref."""
    import hashlib as _hashlib
    digest = _hashlib.md5(str(shipment_ref).encode()).hexdigest()
    prefix = str(int(digest[:6], 16) % 1000).zfill(3)
    suffix = str(int(digest[6:14], 16) % 100000000).zfill(8)
    return f"{prefix}-{suffix}"


def generate_awb(shipment: dict, company_name='My Freight Co') -> bytes:
    if not REPORTLAB_AVAILABLE:
        return _text_pdf("Air Waybill", _fallback_document_lines(shipment, company_name, "Air Waybill"))

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4,
                            leftMargin=15*mm, rightMargin=15*mm,
                            topMargin=15*mm, bottomMargin=15*mm)
    s   = _styles()
    ref      = shipment.get('shipment_ref', 'N/A')
    awb_num  = _awb_number(ref)
    now      = datetime.utcnow().strftime('%Y-%m-%d')
    currency = shipment.get('currency', 'USD')
    freight  = float(shipment.get('freight_rate') or 0)
    weight   = float(shipment.get('weight_kg') or 0)
    declared = f"{currency} {freight:,.2f}" if freight else "NVD"
    story    = []

    story.append(_header_table(s, company_name, 'AIR WAYBILL', f'AWB# {awb_num}', f'Issue Date: {now}', BLUE))
    story.append(Spacer(1, 5*mm))

    # Shipper / Consignee
    story.append(_party_table(s,
        shipment.get('shipper_name'),   shipment.get('shipper_address'),
        shipment.get('consignee_name'), shipment.get('consignee_address')))
    story.append(Spacer(1, 4*mm))

    # Routing
    route_data = [
        ['ISSUING CARRIER', 'DEPARTURE AIRPORT', 'DESTINATION AIRPORT', 'FLIGHT / ETD', 'INCOTERM'],
        [
            shipment.get('carrier_name', '—'),
            shipment.get('origin_port', '—'),
            shipment.get('destination_port', '—'),
            shipment.get('etd', '—'),
            shipment.get('incoterm', 'DAP'),
        ]
    ]
    rt = Table(route_data, colWidths=[38*mm, 37*mm, 40*mm, 37*mm, 28*mm-4])
    rt.setStyle(_tbl_style())
    story.append(rt)
    story.append(Spacer(1, 4*mm))

    # Cargo details
    chargeable = round(max(weight, (float(shipment.get('volume_cbm') or 0) * 167)), 1)
    rate_per_kg = round(freight / chargeable, 4) if chargeable else 0.0
    cargo_data = [
        ['PIECES', 'NATURE OF GOODS', 'GROSS WEIGHT (KG)', 'CHARGEABLE WT (KG)', 'RATE/KG', 'TOTAL'],
        [
            '1',
            shipment.get('cargo_description', '—'),
            f"{weight:,.1f}",
            f"{chargeable:,.1f}",
            f"{currency} {rate_per_kg:,.4f}",
            f"{currency} {freight:,.2f}",
        ]
    ]
    ct = Table(cargo_data, colWidths=[14*mm, 56*mm, 32*mm, 32*mm, 28*mm, 28*mm])
    ct.setStyle(_tbl_style())
    story.append(ct)
    story.append(Spacer(1, 4*mm))

    # Charges
    fuel_surcharge = round(freight * 0.15, 2)
    total_charges  = round(freight + fuel_surcharge, 2)
    charge_data = [
        ['CHARGE TYPE', 'CURRENCY', 'AMOUNT'],
        ['Air Freight',   currency, f'{freight:,.2f}'],
        ['Fuel Surcharge (15%)', currency, f'{fuel_surcharge:,.2f}'],
        ['TOTAL CHARGES', currency, f'{total_charges:,.2f}'],
    ]
    cht = Table(charge_data, colWidths=[100*mm, 40*mm, 50*mm])
    cht.setStyle(TableStyle([
        *_tbl_style().getCommands(),
        ('FONTNAME', (0, -1), (-1, -1), 'Helvetica-Bold'),
        ('BACKGROUND', (0, -1), (-1, -1), LIGHT),
    ]))
    story.append(cht)
    story.append(Spacer(1, 4*mm))

    # Declared value + special handling
    meta_data = [
        ['DECLARED VALUE FOR CUSTOMS', 'SPECIAL HANDLING / NOTES'],
        [declared, shipment.get('notes', '') or 'None'],
    ]
    mt = Table(meta_data, colWidths=[95*mm, 95*mm])
    mt.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), LIGHT),
        ('FONTNAME',   (0,0), (-1,0), 'Helvetica-Bold'),
        ('FONTSIZE',   (0,0), (-1,-1), 8),
        ('BOX',        (0,0), (-1,-1), 0.5, colors.HexColor('#dee2e6')),
        ('LINEAFTER',  (0,0), (0,-1), 0.5, colors.HexColor('#dee2e6')),
        ('TOPPADDING', (0,0), (-1,-1), 4),
        ('BOTTOMPADDING', (0,0), (-1,-1), 4),
        ('LEFTPADDING',   (0,0), (-1,-1), 6),
    ]))
    story.append(mt)
    story.append(Spacer(1, 8*mm))

    # Signature boxes
    sig_data = [[
        Paragraph('SHIPPER SIGNATURE\n\n\n\n________________________', s['Small']),
        Paragraph('CARRIER SIGNATURE\n\n\n\n________________________', s['Small']),
        Paragraph('DATE\n\n\n\n________________________', s['Small']),
    ]]
    st = Table(sig_data, colWidths=[63*mm, 63*mm, 64*mm])
    st.setStyle(TableStyle([
        ('BOX', (0,0), (-1,-1), 0.5, GREY),
        ('LINEBEFORE', (1,0), (2,-1), 0.5, GREY),
        ('TOPPADDING', (0,0), (-1,-1), 6),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
        ('LEFTPADDING', (0,0), (-1,-1), 6),
    ]))
    story.append(st)
    story.append(Spacer(1, 4*mm))
    story.append(Paragraph(
        'This Air Waybill is a non-negotiable transport document issued under IATA conditions. '
        'Chargeable weight = greater of actual gross weight or volumetric weight (volume cbm × 167). '
        '| Generated by TMS',
        s['Small']))

    doc.build(story)
    return buf.getvalue()


def generate_customer_invoice(invoice: dict, shipment: dict, company_name='My Freight Co') -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4,
                            leftMargin=15*mm, rightMargin=15*mm,
                            topMargin=15*mm, bottomMargin=15*mm)
    s = _styles()

    invoice_id = int(invoice.get('id') or 0)
    invoice_number = f"CINV-{invoice_id:05d}" if invoice_id else f"CINV-{shipment.get('shipment_ref', 'N/A')}"
    invoice_date = (invoice.get('created_at') or '').strip()[:10] or datetime.utcnow().strftime('%Y-%m-%d')
    due_date = (invoice.get('due_date') or '').strip()[:10] or '-'
    paid_at = (invoice.get('paid_at') or '').strip()[:10] or '-'
    customer_name = invoice.get('customer_name') or shipment.get('shipper_name') or '-'
    if customer_name == shipment.get('consignee_name'):
        customer_address = shipment.get('consignee_address') or ''
    else:
        customer_address = shipment.get('shipper_address') or ''

    status = invoice.get('status') or 'Draft'
    currency = invoice.get('currency') or shipment.get('currency') or 'USD'
    amount = float(invoice.get('amount') or 0)
    exchange_rate = float(invoice.get('exchange_rate') or 1)
    route_label = f"{shipment.get('origin_port') or '-'} -> {shipment.get('destination_port') or '-'}"
    story = []

    story.append(_header_table(s, company_name, 'CUSTOMER INVOICE', invoice_number, f'Date: {invoice_date}', BLUE))
    story.append(Spacer(1, 5*mm))

    parties = Table(
        [
            [Paragraph('ISSUED BY', s['Label']), Paragraph('BILLED TO', s['Label'])],
            [Paragraph(company_name or '-', s['Bold9']), Paragraph(customer_name, s['Bold9'])],
            [
                Paragraph('Freight services invoice', s['Value']),
                Paragraph(customer_address, s['Value']),
            ],
        ],
        colWidths=[95*mm, 95*mm],
    )
    parties.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), LIGHT),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 8),
        ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#dee2e6')),
        ('LINEAFTER', (0, 0), (0, -1), 0.5, colors.HexColor('#dee2e6')),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
    ]))
    story.append(parties)
    story.append(Spacer(1, 4*mm))

    meta = [
        ['SHIPMENT REF', 'STATUS', 'DUE DATE', 'PAID AT', 'EXCHANGE RATE'],
        [
            shipment.get('shipment_ref', '-'),
            status,
            due_date,
            paid_at,
            f"{exchange_rate:,.4f}",
        ],
    ]
    meta_table = Table(meta, colWidths=[42*mm, 32*mm, 34*mm, 34*mm, 48*mm])
    meta_table.setStyle(_tbl_style())
    story.append(meta_table)
    story.append(Spacer(1, 4*mm))

    items = [
        ['#', 'DESCRIPTION', 'ROUTE', 'CONTAINERS', 'TOTAL'],
        [
            '1',
            shipment.get('cargo_description', 'Freight services'),
            route_label,
            shipment.get('containers', '-') or '-',
            f'{currency} {amount:,.2f}',
        ],
    ]
    items_table = Table(items, colWidths=[8*mm, 60*mm, 52*mm, 32*mm, 38*mm])
    items_table.setStyle(_tbl_style())
    story.append(items_table)
    story.append(Spacer(1, 3*mm))

    totals = [
        ['', '', '', 'SUBTOTAL:', f'{currency} {amount:,.2f}'],
        ['', '', '', 'TOTAL DUE:', f'{currency} {amount:,.2f}'],
    ]
    totals_table = Table(totals, colWidths=[8*mm, 60*mm, 52*mm, 32*mm, 38*mm])
    totals_table.setStyle(TableStyle([
        ('FONTNAME', (3, 1), (4, 1), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 8),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ('LINEABOVE', (3, 1), (4, 1), 1, BLUE),
        ('ALIGN', (3, 0), (4, -1), 'RIGHT'),
    ]))
    story.append(totals_table)
    story.append(Spacer(1, 8*mm))
    story.append(Paragraph(
        'Customer invoice generated from shipment data. Exchange rate is recorded for accounting sync.',
        s['Small']))
    story.append(Spacer(1, 10*mm))
    story.append(Paragraph('Authorised Signature: ________________________      Date: ___________', s['Small']))

    doc.build(story)
    return buf.getvalue()
