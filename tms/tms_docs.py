def _styles():
    s = getSampleStyleSheet()
    s.add(ParagraphStyle('Title2',   fontName='Helvetica-Bold', fontSize=18, textColor=DARK,  spaceAfter=2))
    s.add(ParagraphStyle('Sub',      fontName='Helvetica',      fontSize=9,  textColor=GREY,  spaceAfter=2))
    s.add(ParagraphStyle('Label',    fontName='Helvetica-Bold', fontSize=8,  textColor=GREY))
    s.add(ParagraphStyle('Value',    fontName='Helvetica',      fontSize=9,  textColor=DARK))
    s.add(ParagraphStyle('Bold9',    fontName='Helvetica-Bold', fontSize=9,  textColor=DARK))
    s.add(ParagraphStyle('Center9',  fontName='Helvetica',      fontSize=9,  textColor=DARK,  alignment=TA_CENTER))
    s.add(ParagraphStyle('Right9',   fontName='Helvetica',      fontSize=9,  textColor=DARK,  alignment=TA_RIGHT))
    s.add(ParagraphStyle('Small',    fontName='Helvetica',      fontSize=7,  textColor=GREY))
    return s

def _tbl_style(header_bg=BLUE):
    return TableStyle([
        ('BACKGROUND', (0,0), (-1,0), header_bg),
        ('TEXTCOLOR',  (0,0), (-1,0), WHITE),
        ('FONTNAME',   (0,0), (-1,0), 'Helvetica-Bold'),
        ('FONTSIZE',   (0,0), (-1,-1), 8),
        ('ROWBACKGROUNDS', (0,1), (-1,-1), [WHITE, LIGHT]),
        ('GRID',       (0,0), (-1,-1), 0.4, colors.HexColor('#dee2e6')),
        ('VALIGN',     (0,0), (-1,-1), 'MIDDLE'),
        ('TOPPADDING', (0,0), (-1,-1), 4),
        ('BOTTOMPADDING', (0,0), (-1,-1), 4),
        ('LEFTPADDING',   (0,0), (-1,-1), 6),
    ])

def _header_table(s, company_name, doc_type, ref, date_str, color=BLUE):
    """Top banner with company name left, document type right."""
    data = [[
        Paragraph(f'<font color="#0d6efd"><b>{company_name}</b></font>', s['Title2']),
        Paragraph(f'<b>{doc_type}</b><br/><font color="#6c757d">{ref}</font><br/><font color="#6c757d">{date_str}</font>', s['Right9'])
    ]]
    t = Table(data, colWidths=[95*mm, 95*mm])
    t.setStyle(TableStyle([
        ('VALIGN', (0,0), (-1,-1), 'TOP'),
        ('LINEBELOW', (0,0), (-1,-1), 1.2, color),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
    ]))
    return t

def _party_table(s, shipper_name, shipper_addr, consignee_name, consignee_addr):
    data = [
        [Paragraph('SHIPPER / EXPORTER', s['Label']), Paragraph('CONSIGNEE / IMPORTER', s['Label'])],
        [Paragraph(shipper_name or '—', s['Bold9']),   Paragraph(consignee_name or '—', s['Bold9'])],
        [Paragraph(shipper_addr or '',  s['Value']),   Paragraph(consignee_addr or '',  s['Value'])],
    ]
    t = Table(data, colWidths=[95*mm, 95*mm])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), LIGHT),
        ('FONTNAME',   (0,0), (-1,0), 'Helvetica-Bold'),
        ('FONTSIZE',   (0,0), (-1,-1), 8),
        ('BOX',        (0,0), (-1,-1), 0.5, colors.HexColor('#dee2e6')),
        ('LINEAFTER',  (0,0), (0,-1), 0.5, colors.HexColor('#dee2e6')),
        ('TOPPADDING', (0,0), (-1,-1), 4),
        ('BOTTOMPADDING', (0,0), (-1,-1), 4),
        ('LEFTPADDING',   (0,0), (-1,-1), 6),
    ]))
    return t


# ── BOL ───────────────────────────────────────────────────────────────────────
def generate_bol(shipment: dict, company_name='My Freight Co') -> bytes:
    if not REPORTLAB_AVAILABLE:
        return _text_pdf("Bill of Lading", _fallback_document_lines(shipment, company_name, "Bill of Lading"))

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4,
                            leftMargin=15*mm, rightMargin=15*mm,
                            topMargin=15*mm, bottomMargin=15*mm)
    s   = _styles()
    ref = shipment.get('shipment_ref', 'N/A')
    now = datetime.utcnow().strftime('%Y-%m-%d')
    story = []

    story.append(_header_table(s, company_name, 'BILL OF LADING', f'BOL# {ref}', f'Date: {now}'))
    story.append(Spacer(1, 5*mm))
    story.append(_party_table(s,
        shipment.get('shipper_name'),    shipment.get('shipper_address'),
        shipment.get('consignee_name'),  shipment.get('consignee_address')))
    story.append(Spacer(1, 4*mm))

    # Route info
    route_data = [
        ['PORT OF LOADING', 'PORT OF DISCHARGE', 'CARRIER', 'ETD', 'ETA', 'INCOTERM'],
        [
            shipment.get('origin_port', '—'),
            shipment.get('destination_port', '—'),
            shipment.get('carrier_name', '—'),
            shipment.get('etd', '—'),
            shipment.get('eta', '—'),
            shipment.get('incoterm', 'FOB'),
        ]
    ]
    rt = Table(route_data, colWidths=[35*mm, 35*mm, 35*mm, 25*mm, 25*mm, 35*mm])
    rt.setStyle(_tbl_style())
    story.append(rt)
    story.append(Spacer(1, 4*mm))

    # Cargo
    cargo_data = [
        ['DESCRIPTION OF GOODS', 'CONTAINER/MARKS', 'WEIGHT (KG)', 'VOLUME (CBM)'],
        [
            shipment.get('cargo_description', '—'),
            shipment.get('containers', '—'),
            f"{shipment.get('weight_kg') or 0:,.1f}",
            f"{shipment.get('volume_cbm') or 0:,.2f}",
        ]
    ]
    ct = Table(cargo_data, colWidths=[70*mm, 50*mm, 30*mm, 30*mm-4])
    ct.setStyle(_tbl_style())
    story.append(ct)
    story.append(Spacer(1, 8*mm))

    # Freight charges
    freight = shipment.get('freight_rate') or 0
    currency = shipment.get('currency', 'USD')
    charge_data = [
        ['FREIGHT CHARGES', 'CURRENCY', 'AMOUNT', 'PAYMENT TERMS'],
        ['Ocean Freight', currency, f'{freight:,.2f}', 'PREPAID'],
    ]
    cht = Table(charge_data, colWidths=[70*mm, 30*mm, 40*mm, 50*mm])
    cht.setStyle(_tbl_style())
    story.append(cht)
    story.append(Spacer(1, 8*mm))

    # Signature boxes
    sig_data = [[
        Paragraph('SHIPPER SIGNATURE\n\n\n\n________________________', s['Small']),
        Paragraph('CARRIER SIGNATURE\n\n\n\n________________________', s['Small']),
        Paragraph('CONSIGNEE SIGNATURE\n\n\n\n________________________', s['Small']),
    ]]
    st = Table(sig_data, colWidths=[63*mm, 63*mm, 64*mm])
    st.setStyle(TableStyle([
        ('BOX', (0,0), (-1,-1), 0.5, GREY),
        ('LINEBEFORE', (1,0), (2,-1), 0.5, GREY),
        ('TOPPADDING', (0,0), (-1,-1), 6),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
        ('LEFTPADDING', (0,0), (-1,-1), 6),
    ]))
    story.append(st)
    story.append(Spacer(1, 4*mm))
    story.append(Paragraph('This document is issued subject to applicable international conventions and carrier tariffs. | Generated by TMS', s['Small']))

    doc.build(story)
    return buf.getvalue()


